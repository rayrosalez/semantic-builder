WRAP = 88
_PLAIN = re.compile(r"^[A-Za-z_][A-Za-z0-9_\-]*$")


# ---------- YAML (fixed layout, so emitted by hand for stable diffs) ----------

def key(k: str) -> str:
    return k if _PLAIN.match(k) else json.dumps(k)


def scalar(v: str | None, indent: int) -> str:
    """Inline for short single-line text; wrapped block scalar otherwise."""
    if v is None or v == "":
        return '""'
    pad = " " * indent
    if "\n" in v:
        return "|-\n" + "\n".join(pad + line if line else "" for line in v.split("\n"))
    if len(v) + indent > WRAP or v != v.strip() or not _safe_inline(v):
        lines = textwrap.wrap(v, max(WRAP - indent, 40), break_long_words=False, break_on_hyphens=False)
        if v == " ".join(lines):  # folding restores single spaces exactly
            return ">-\n" + "\n".join(pad + line for line in lines)
        return json.dumps(v)
    return v


def _safe_inline(v: str) -> bool:
    return (not v[0] in "!&*-?{}[]|>'\"%@`#,:" and ": " not in v and " #" not in v
            and v.lower() not in ("true", "false", "yes", "no", "null", "on", "off", "~")
            and not re.match(r"^[\d.+-]", v))


def render(catalog: str, schema: str, schema_comment: str | None, tables: dict, targets: dict,
           plan_id: str, week_of: str, source: str) -> str:
    """tables: {table: {"description": str|None, "columns": {name: str|None}}} in column order."""
    out = [
        f"# plan_id: {plan_id}",
        f"# week_of: {week_of}",
        f"# catalog: {catalog}",
        f"# schema: {schema}",
        "# Generated by Semantic Builder from the descriptions live in Unity Catalog.",
        "variables:",
        "  catalog:",
        "    description: Target catalog",
        "  schema:",
        "    description: Target schema",
        "targets:",
    ]
    for name, t in (targets or {"default": {"catalog": catalog, "schema": schema}}).items():
        out += [f"  {key(name)}:", "    variables:",
                f"      catalog: {key(t['catalog'])}", f"      schema: {key(t['schema'])}"]
    out += [
        "catalog: ${var.catalog}",
        "schema: ${var.schema}",
        f"schema_description: {scalar(schema_comment, 2)}",
        "schema_tags: {}",
        f"source: {scalar(source, 2)}",
        "tables:",
    ]
    for tname, t in tables.items():
        out += [f"  {key(tname)}:", f"    description: {scalar(t['description'], 6)}", "    columns:"]
        for cname, desc in t["columns"].items():
            out += [f"      {key(cname)}:", f"        description: {scalar(desc, 10)}", "        tags: {}"]
        if not t["columns"]:
            out[-1] = "    columns: {}"
        out.append("    tags: {}")
    if not tables:
        out[-1] = "tables: {}"
    return "\n".join(out) + "\n"


# ---------- GitHub ----------

class GitHub:
    def __init__(self, repo: str, token: str, api: str = "https://api.github.com"):
        self.repo, self._token, self.api = repo, token, api.rstrip("/")

    def call(self, method: str, path: str, body: dict | None = None):
        req = urllib.request.Request(
            f"{self.api}/repos/{self.repo}{path}", method=method,
            data=json.dumps(body).encode() if body is not None else None,
            headers={"Authorization": f"Bearer {self._token}", "Accept": "application/vnd.github+json",
                     "X-GitHub-Api-Version": "2022-11-28", "User-Agent": "semantic-builder"})
        try:
            with urllib.request.urlopen(req, timeout=60) as r:
                return json.loads(r.read() or b"null")
        except urllib.error.HTTPError as e:
            if e.code == 404 and method == "GET":
                return None
            # The message is GitHub's; the token is only ever in the request header.
            raise RuntimeError(f"GitHub {method} {path} -> {e.code}: {e.read()[:300]!r}") from None

    def file(self, path: str, ref: str) -> tuple[str | None, str | None]:
        got = self.call("GET", f"/contents/{path}?ref={ref}")
        if not got:
            return None, None
        return base64.b64decode(got["content"]).decode(), got["sha"]

    def open_pr(self, base: str, branch: str, files: dict[str, str], title: str, body: str) -> str | None:
        changed = {p: c for p, c in files.items() if self.file(p, base)[0] != c}
        if not changed:
            print("YAML already matches", base, "- no pull request needed")
            return None
        sha = self.call("GET", f"/git/ref/heads/{base}")["object"]["sha"]
        self.call("POST", "/git/refs", {"ref": f"refs/heads/{branch}", "sha": sha})
        for path, content in changed.items():
            _, file_sha = self.file(path, branch)
            self.call("PUT", f"/contents/{path}", {
                "message": f"Semantic Builder: update {path}", "branch": branch,
                "content": base64.b64encode(content.encode()).decode(),
                **({"sha": file_sha} if file_sha else {})})
        pr = self.call("POST", "/pulls", {"title": title, "head": branch, "base": base, "body": body})
        return pr["html_url"]


# ---------- Spark side ----------

def q(*parts: str) -> str:
    return ".".join(f"`{x.replace('`', '``')}`" for x in parts)


def schema_yaml(spark, queue: str, catalog: str, schema: str, targets: dict, run_id: str) -> str:
    p = {"s": schema}
    schema_comment = next(iter(r.comment for r in spark.sql(
        f"SELECT comment FROM {q(catalog)}.information_schema.schemata WHERE schema_name = :s",
        args=p).collect()), None)
    tables = {r.table_name: {"description": r.comment, "columns": {}} for r in spark.sql(
        f"SELECT table_name, comment FROM {q(catalog)}.information_schema.tables "
        "WHERE table_schema = :s AND table_name NOT LIKE '\\_\\_%' ORDER BY table_name", args=p).collect()}
    for r in spark.sql(
            f"SELECT table_name, column_name, comment FROM {q(catalog)}.information_schema.columns "
            "WHERE table_schema = :s ORDER BY table_name, ordinal_position", args=p).collect():
        if r.table_name in tables:
            tables[r.table_name]["columns"][r.column_name] = r.comment
    last = spark.sql(
        f"SELECT batch_id, note FROM {queue} WHERE catalog_name = :c AND schema_name = :s "
        "AND status = 'APPLIED' AND requested_by = 'dictionary-import' ORDER BY applied_at DESC LIMIT 1",
        args={"c": catalog, "s": schema}).collect()
    plan_id = last[0].batch_id if last else f"semantic-builder-run-{run_id}"
    m = re.search(r"week_of (\S+)", last[0].note or "") if last else None
    week_of = m.group(1) if m else dt.date.today().isoformat()
    return render(catalog, schema, schema_comment, tables, targets, plan_id, week_of, "semantic-builder")


def in_scope_schemas(spark, scope: list[str]) -> list[tuple[str, str]]:
    out = []
    for catalog in sorted({s.split(".")[0] for s in scope}):
        for r in spark.sql(f"SELECT schema_name FROM {q(catalog)}.information_schema.schemata").collect():
            if queue_sql.schema_in_scope(scope, catalog, r.schema_name):
                out.append((catalog, r.schema_name))
    return sorted(out)


def parse_args(argv=None):
    p = argparse.ArgumentParser()
    p.add_argument("--staging_catalog", required=True)
    p.add_argument("--staging_schema", required=True)
    p.add_argument("--scope", default="")
    p.add_argument("--run_id", default="")
    p.add_argument("--github_repo", default="")
    p.add_argument("--github_base_branch", default="main")
    p.add_argument("--github_path_template", default="metadata/{schema}.yaml")
    p.add_argument("--github_api_url", default="https://api.github.com")
    p.add_argument("--github_secret_scope", default="")
    p.add_argument("--github_secret_key", default="")
    p.add_argument("--export_targets", default="")
    # parse_known_args: "run now with different parameters" passes the apply task's
    # parameters to every python task in the job.
    return p.parse_known_args(argv)[0]


def main(argv=None) -> None:
    from databricks.sdk import WorkspaceClient
    from pyspark.sql import SparkSession

    args = parse_args(argv)
    if not args.github_repo or not args.github_secret_scope or not args.github_secret_key:
        raise ValueError("github_repo, github_secret_scope and github_secret_key must all be set")
    spark = SparkSession.builder.getOrCreate()
    queue = f"{q(args.staging_catalog, args.staging_schema)}.`metadata_change_requests`"
    targets = json.loads(args.export_targets) if args.export_targets.strip() else {}
    files = {
        args.github_path_template.format(catalog=c, schema=s):
            schema_yaml(spark, queue, c, s, targets, args.run_id or "manual")
        for c, s in in_scope_schemas(spark, queue_sql.parse_scope(args.scope))
    }
    print(f"Rendered {len(files)} file(s): {', '.join(files)}")
    secret = WorkspaceClient().secrets.get_secret(args.github_secret_scope, args.github_secret_key)
    token = base64.b64decode(secret.value).decode().strip()
    gh = GitHub(args.github_repo, token, args.github_api_url)
    stamp = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%d-%H%M%S")
    url = gh.open_pr(args.github_base_branch, f"semantic-builder/export-{stamp}", files,
                     f"Semantic Builder: metadata export {stamp}",
                     "Descriptions currently live in Unity Catalog, exported by the Semantic Builder "
                     f"apply job (run {args.run_id or 'manual'}). These changes are already applied; "
                     "merging records them.")
    if url:
        print("Opened pull request:", url)


if __name__ == "__main__":
    main()
