"""Optional: export the live descriptions to YAML and open a GitHub pull request.

Off by default (bundle variable github_export_enabled). When on, it runs after
apply_changes and writes one file per in-scope schema in the DictionarySpec
layout, then opens a PR against --github_base_branch. It never pushes to the
base branch. The token is read from a secret scope and never printed.

If the customer's own GitHub Action also applies metadata when this PR merges,
the change lands twice; one side should only keep the record.

  --github_path_template   e.g. metadata/{schema}.yaml  ({catalog}, {schema})
  --export_targets         JSON {"dev": {"catalog": .., "schema": ..}, ...} for
                           the file's targets block; empty = the live catalog only
"""
